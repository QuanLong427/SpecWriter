import { existsSync, readFileSync } from 'node:fs';
import { atomicWrite, chapterId, hash, json, safePath } from './files.js';
import { currentFacts, replay, trustedPrefix } from './memory.js';
import { entityLabel } from './entity-reference.js';
import type { Revision, WorkItem } from './types.js';

export interface DirtyFile { chapter: number; path: string; kind: 'modified' | 'missing' | 'outdated' }
export function dirtyFiles(root: string, revisions: Revision[], knownHashes?: Map<number, Set<string>>): DirtyFile[] {
  let marker: { chapters?: { chapter: number; hash: string }[] } = {};
  try { marker = JSON.parse(readFileSync(safePath(root, '.specwriter', 'projection.json'), 'utf8')); } catch { /* missing marker */ }
  return revisions.flatMap<DirtyFile>(item => {
    const relative = `manuscript/chapters/${chapterId(item.chapter)}.md`;
    const path = safePath(root, relative);
    if (!existsSync(path)) return [{ chapter: item.chapter, path: relative, kind: 'missing' as const }];
    const actual = hash(readFileSync(path, 'utf8'));
    if (actual === item.bodyHash) return [];
    const previous = marker.chapters?.find(row => row.chapter === item.chapter)?.hash;
    // After a DB commit/crash, an unchanged earlier projection is safe to regenerate.
    const outdated = actual === previous && Boolean(knownHashes?.get(item.chapter)?.has(actual));
    return [{ chapter: item.chapter, path: relative, kind: outdated ? 'outdated' as const : 'modified' as const }];
  });
}
export function projectViews(root: string, revisions: Revision[], works: WorkItem[], generation: number): void {
  const trusted = trustedPrefix(revisions);
  const state = replay(revisions);
  const banner = '<!-- Generated by SpecWriter. Rebuild with specwriter sync. -->\n';
  const disclaimer = `记忆已同步到第 ${state.atChapter} 章。需要重审的后续正文不参与当前记忆。\n\n`;
  const facts = currentFacts(state);
  const renderFact = (item: typeof facts[number]): string => `- ${entityLabel(state, item.subject)} / ${item.predicate}：${item.object}（第 ${item.sourceChapter} 章，版本 ${item.sourceRevision}，原文第 ${item.evidenceLine} 行）`;
  const write = (name: string, body: string): void => atomicWrite(safePath(root, 'specwriter', 'memory', 'views', name), banner + body);
  write('current-state.md', '# 当前故事状态\n\n' + disclaimer + facts.filter(item => item.scope === 'world').map(renderFact).join('\n') + '\n');
  write('character-beliefs.md', '# 人物认知\n\n' + disclaimer + facts.filter(item => item.scope === 'belief').map(item => `- ${entityLabel(state, item.holder!)} 相信：${entityLabel(state, item.subject)} / ${item.predicate}：${item.object}（第 ${item.sourceChapter} 章）`).join('\n') + '\n');
  write('pending-hooks.md', '# 伏笔与承诺\n\n' + disclaimer + state.hooks.map(item => `- ${item.id} [${item.status}] ${item.description}（起于第 ${item.startChapter} 章，最近证据第 ${item.sourceChapter} 章）`).join('\n') + '\n');
  write('timeline.md', '# 故事时间线\n\n' + disclaimer + state.timeline.map(item => `- ${item.time}：${item.event}（来源第 ${item.sourceChapter} 章）`).join('\n') + '\n');
  write('chapter-summaries.md', '# 已接纳章节摘要\n\n' + disclaimer + state.summaries.map(item => `## 第 ${item.chapter} 章：${item.title}\n\n${item.summary}\n`).join('\n'));
  write('entities.md', '# 实体与别名\n\n' + disclaimer + state.entities.map(entity => `- ${entity.id} [${entity.type}] ${entity.name}（别名：${entity.aliases.join('、')}）：${entity.description}（来源第 ${entity.sourceChapter} 章）`).join('\n') + '\n');
  write('events.md', '# 事件与因果\n\n' + disclaimer + state.episodes.map(event => `- ${event.id} [${event.scope}${event.holder ? `:${event.holder}` : ''}] ${event.description}（原因：${event.causes.join('、') || '未确立'}；来源第 ${event.sourceChapter} 章）`).join('\n') + '\n');
  write('resources.md', '# 资源账本\n\n' + disclaimer + state.resources.map(resource => `- ${entityLabel(state, resource.entity)} / ${resource.resource}：${resource.amount}（来源第 ${resource.sourceChapter} 章）`).join('\n') + '\n');
  for (const work of works) {
    if (work.status === 'archived') continue; // Archives are historical snapshots, not current projections.
    const directory = 'work';
    const completed = (chapter: number): boolean => revisions.some(item => item.chapter === chapter && !item.stale && item.chapter <= trusted.length);
    const lines = Array.from({ length: work.toChapter - work.fromChapter + 1 }, (_, index) => work.fromChapter + index)
      .map(chapter => `- [${completed(chapter) ? 'x' : ' '}] 第 ${chapter} 章：正文接纳与记忆同步`);
    atomicWrite(safePath(root, 'specwriter', directory, work.id, 'tasks.md'), banner + `# ${work.title}\n\n状态：${work.status}\n\n` + lines.join('\n') + '\n');
  }
  // Write the completion marker last so interrupted projection work remains detectable.
  atomicWrite(safePath(root, '.specwriter', 'projection.json'), json({ generation, trustedThrough: trusted.length, chapters: revisions.map(item => ({ chapter: item.chapter, revision: item.id, hash: item.bodyHash, stale: item.stale })) }));
}
